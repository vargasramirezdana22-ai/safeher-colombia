def normalizar_texto(txt):
    txt = str(txt or "").strip().upper()
    txt = "".join(
        c for c in unicodedata.normalize("NFD", txt)
        if unicodedata.category(c) != "Mn"
    )
    return txt.replace("  ", " ")

def guia_basica(dep, muni):
    return {
        "categoria": "Guía turística básica",
        "hoteles": [],
        "restaurantes": [],
        "sitios_turisticos": [],
        "actividades": [],
        "dato_curioso": f"{str(muni).title()} es un municipio ubicado en el departamento de {str(dep).title()}, Colombia.",
        "mejor_epoca": "Temporada seca entre diciembre y marzo, aunque puede variar según la región.",
        "consejos": [
            "Usar transporte autorizado.",
            "Consultar clima y estado de vías antes de viajar.",
            "Evitar zonas solas de noche.",
            "Confirmar precios antes de reservar."
        ]
    }

def obtener_guia(dep, muni):
    dep_norm = normalizar_texto(dep)
    muni_norm = normalizar_texto(muni)

    # búsqueda exacta normalizada por departamento y municipio
    for dep_key, municipios in GUIAS_COLOMBIA.items():
        if normalizar_texto(dep_key) == dep_norm:
            for muni_key, guia in municipios.items():
                if normalizar_texto(muni_key) == muni_norm:
                    return guia
            return guia_basica(dep, muni)

    # búsqueda por municipio, por si el departamento viene distinto
    for dep_key, municipios in GUIAS_COLOMBIA.items():
        for muni_key, guia in municipios.items():
            if normalizar_texto(muni_key) == muni_norm:
                return guia

    return guia_basica(dep, muni)
